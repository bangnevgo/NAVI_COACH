// ─── Demo Analytics ───
export function getDemoStats() {
  const total = DEMO_CLIENTS.length;
  const active = DEMO_CLIENTS.filter(c => c.status === 'active').length;
  const onProgress = DEMO_CLIENTS.filter(c => c.status === 'on_progress').length;
  const completed = DEMO_CLIENTS.filter(c => c.status === 'completed').length;
  const inactive = DEMO_CLIENTS.filter(c => c.status === 'inactive').length;
  const totalSessions = DEMO_CLIENTS.reduce((sum, c) => sum + c.totalSessions, 0);
  const avgProgress = Math.round(DEMO_CLIENTS.reduce((sum, c) => sum + c.progress, 0) / total);

  return {
    total,
    active: active + onProgress,
    onProgress,
    completed,
    inactive,
    totalSessions,
    avgProgress,
  };
}

// ─── Demo Phase Distribution ───
export function getDemoPhaseDistribution() {
  const phaseMap = new Map<string, number>();
  DEMO_CLIENTS.forEach(c => {
    const count = phaseMap.get(c.phase) || 0;
    phaseMap.set(c.phase, count + 1);
  });
  return Array.from(phaseMap.entries()).map(([name, value]) => ({ name, value }));
}

