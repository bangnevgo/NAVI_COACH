// ─── Upcoming Sessions (across all demo clients) ───
export function getDemoUpcomingSessions() {
  return DEMO_CLIENTS
    .filter(c => c.nextSession && c.status !== 'inactive' && c.status !== 'completed')
    .map(c => ({
      id: `upcoming-${c.id}`,
      clientName: c.name,
      clientId: c.id,
      date: c.nextSession!,
      type: 'Sesi Coaching',
      phase: c.phase,
    }))
    .sort((a, b) => new Date(a.date).getTime() - new Date(b.date).getTime())
    .slice(0, 5);
}

